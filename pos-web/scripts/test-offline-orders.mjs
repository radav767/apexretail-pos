import { readFile } from "node:fs/promises";
import ts from "typescript";
import assert from "node:assert/strict";
const source = await readFile(new URL("../src/business/offlineOrders.ts", import.meta.url), "utf8");
const js = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.ES2022, target: ts.ScriptTarget.ES2022 } }).outputText;
const { OfflineOrderOutbox } = await import(`data:text/javascript;base64,${Buffer.from(js).toString("base64")}`);
const map = new Map();
const storage = { get length() { return map.size; }, key: i => [...map.keys()][i] ?? null, getItem: key => map.get(key) ?? null, setItem: (key, value) => map.set(key, value) };
const identity = { company: "company-a", employee: "waiter-a", device: "register-a" };
const queue = new OfflineOrderOutbox(storage, identity);
const command = { id: "command-a", endpoint: "/operations/offline/drafts", payload: { captured_at: "2026-10-19T12:00:00Z", original: "unchanged" } };
queue.enqueue(command);
assert.equal(new OfflineOrderOutbox(storage, { ...identity, employee: "waiter-b" }).list().length, 0);
assert.equal(new OfflineOrderOutbox(storage, identity).list().length, 1); // Restart.
await queue.synchronize(async () => { throw new Error("timeout after server commit"); });
assert.equal(queue.list()[0].status, "pending"); assert.deepEqual(queue.list()[0].payload, command.payload);
await queue.synchronize(async () => { throw { response: { status: 409, data: { detail: "Order changed" } } }; });
assert.equal(queue.list()[0].status, "review"); assert.equal(map.size, 1);
let delivered;
await queue.synchronize(async (_, payload) => { delivered = payload; return { already_synchronized: true, order: { id: "order-a" } }; });
assert.deepEqual(delivered, command.payload); assert.equal(queue.list()[0].status, "acknowledged");
await queue.synchronize(async () => assert.fail("acknowledged draft must not resend"));
assert.throws(() => queue.enqueue(command));
assert.throws(() => new OfflineOrderOutbox({ ...storage, setItem() { throw new Error("quota"); } }, identity).enqueue({ ...command, id: "quota" }));
assert.equal(queue.list().length, 1);
queue.enqueue({ ...command, id: "command-b" }); // Separate command key, no shared array rewrite.
assert.equal(queue.list().length, 2);
assert.equal(map.size, 2);
console.log("Offline order outbox: restart, identity isolation, timeout, conflict retention, immutable retry, acknowledgement, quota and append checks passed");
const pricingSource = await readFile(new URL("../src/business/pricing.ts", import.meta.url), "utf8");
const pricingJs = ts.transpileModule(pricingSource, { compilerOptions: { module: ts.ModuleKind.ES2022 } }).outputText;
const decimalSource = await readFile(new URL("../src/decimal.ts", import.meta.url), "utf8");
const decimalJs = ts.transpileModule(decimalSource, { compilerOptions: { module: ts.ModuleKind.ES2022, target: ts.ScriptTarget.ES2022 } }).outputText;
const decimalUrl = `data:text/javascript;base64,${Buffer.from(decimalJs).toString("base64")}`;
const linkedPricing = pricingJs.replace('"../decimal"', JSON.stringify(decimalUrl));
const { checkoutPrice, accumulatedWeightedQuantity } = await import(`data:text/javascript;base64,${Buffer.from(linkedPricing).toString("base64")}`);
const levels = [{ name: "Wholesale", price: "8.00", minimum_quantity: "1" }, { name: "Wholesale", price: "6.00", minimum_quantity: "10" }];
assert.equal(checkoutPrice(levels, "Wholesale", "1", "12.00"), "8.00");
assert.equal(checkoutPrice(levels, "Wholesale", "10", "12.00"), "6.00");
assert.equal(checkoutPrice(levels, "Wholesale", "9", "12.00"), "8.00");
assert.equal(checkoutPrice(levels, undefined, "10", "12.00"), "12.00");
assert.equal(checkoutPrice([], "VIP", "10", "14.00"), "14.00");
console.log("Pricing: tier increases/decreases, variant base restoration and unconfigured-business compatibility passed");
assert.equal(accumulatedWeightedQuantity("0.250", "0.500", "1.000"), "0.750");
assert.equal(accumulatedWeightedQuantity("0.999", "0.001", "1.000"), "1.000");
assert.throws(() => accumulatedWeightedQuantity("0.750", "0.500", "1.000"));
assert.throws(() => accumulatedWeightedQuantity("0.750", "0", "1.000"));
console.log("Weighted cart: repeated additions merge exactly and cannot exceed combined available stock");
