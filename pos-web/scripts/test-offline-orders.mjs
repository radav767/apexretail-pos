await queue.recover(async (_, payload) => { assert.deepEqual(payload, command.payload); throw { response: { status: 404 } }; });
assert.equal(queue.list().find(row => row.id === "recovery").status, "pending");
await queue.recover(async () => "<html>not a receipt</html>");
